"""Langfuse observability, traceability, and automated evaluation metrics for LangGraph workflows."""

from __future__ import annotations

import logging
from typing import Any

from app.config.settings import get_settings
from app.workflow.state import InvestmentState

logger = logging.getLogger("app.workflow")


def create_langfuse_handler(state: InvestmentState) -> Any | None:
    """Create and configure a Langfuse CallbackHandler if credentials are configured."""
    settings = get_settings()
    if not settings.is_langfuse_enabled:
        return None

    try:
        from langfuse.callback import CallbackHandler

        req = state.get("request") or state.get("user_request")
        user_text = getattr(req, "text", None) if req else None
        analysis_type = getattr(req, "analysis_type", None) if req else None
        portfolio_id = getattr(req, "portfolio_id", None) if req else None

        selected = state.get("selected_stock")
        symbol = getattr(selected, "symbol", None) if selected else None

        tags: list[str] = ["investment-board"]
        if analysis_type:
            tags.append(str(analysis_type))
        if symbol:
            tags.append(str(symbol))

        metadata: dict[str, Any] = {}
        if user_text:
            metadata["user_prompt"] = user_text
        if symbol:
            metadata["symbol"] = str(symbol)
        if portfolio_id:
            metadata["portfolio_id"] = str(portfolio_id)

        return CallbackHandler(
            public_key=settings.langfuse_public_key,
            secret_key=settings.langfuse_secret_key,
            host=settings.langfuse_host,
            user_id=str(portfolio_id) if portfolio_id else "anonymous",
            session_id=str(state.get("analysis_id") or state.get("request_id") or "") or None,
            tags=tags,
            metadata=metadata or None,
        )
    except Exception as exc:
        logger.warning("Failed to initialize Langfuse callback handler: %s", exc)
        return None


def record_workflow_evaluations(handler: Any, state: InvestmentState, final_state: InvestmentState) -> None:
    """Compute and submit automated evaluation scores for the completed workflow run."""
    if handler is None:
        return

    try:
        trace_id = getattr(handler, "get_trace_id", lambda: None)()
        if not trace_id:
            return

        langfuse = getattr(handler, "langfuse", None)
        if langfuse is None or not hasattr(langfuse, "score"):
            return

        # 1. Recommendation Confidence Score
        rec = final_state.get("final_recommendation")
        confidence = float(getattr(rec, "confidence", 0.0) or 0.0)
        langfuse.score(
            trace_id=trace_id,
            name="synthesis_confidence",
            value=confidence,
            comment="Confidence score generated by Portfolio Manager synthesis",
        )

        # 2. Evidence Grounding Metric
        evidence_items = list(final_state.get("evidence") or [])
        evidence_count = len(evidence_items)
        # Normalized: 5+ evidence items represents comprehensive grounding (1.0)
        evidence_grounding_score = min(1.0, round(evidence_count / 5.0, 2))
        langfuse.score(
            trace_id=trace_id,
            name="evidence_grounding",
            value=evidence_grounding_score,
            comment=f"Verified empirical evidence items collected: {evidence_count}",
        )

        # 3. Conflict & Critique Resolution Metric
        conflicts = list(final_state.get("conflicts") or [])
        critiques = list(final_state.get("critiques") or [])
        unresolved_critiques = [c for c in critiques if not getattr(c, "resolved", True)]
        error_conflicts = [c for c in conflicts if getattr(c, "severity", "") == "error"]
        total_issues = len(unresolved_critiques) + len(error_conflicts)

        resolution_score = 1.0 if total_issues == 0 else max(0.0, round(1.0 - (total_issues * 0.25), 2))
        langfuse.score(
            trace_id=trace_id,
            name="conflict_resolution",
            value=resolution_score,
            comment=f"Unresolved critiques: {len(unresolved_critiques)}, Error conflicts: {len(error_conflicts)}",
        )

        # 4. Specialist Execution Success Rate
        agent_results = final_state.get("agent_results") or {}
        if isinstance(agent_results, dict) and agent_results:
            successful = sum(1 for res in agent_results.values() if getattr(res, "status", "") == "succeeded")
            success_rate = round(successful / len(agent_results), 2)
            langfuse.score(
                trace_id=trace_id,
                name="agent_success_rate",
                value=success_rate,
                comment=f"Successful specialist agents: {successful}/{len(agent_results)}",
            )

        # Flush metrics to Langfuse
        if hasattr(handler, "flush"):
            handler.flush()

        trace_url = getattr(handler, "get_trace_url", lambda: None)()
        if trace_url:
            logger.info("Langfuse workflow trace: %s", trace_url)

    except Exception as exc:
        logger.warning("Failed to record Langfuse evaluations: %s", exc)
